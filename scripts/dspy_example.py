"""
DSPy Example: Demonstrating Declarative Self-Improving Python

This script shows how DSPy differs from traditional LangChain prompting.
Instead of writing prompt strings, we define "Signatures" and let the
optimizer automatically improve the prompts based on golden answers.

Key Concepts:
- Signature: Defines WHAT to do (inputs/outputs), not HOW to prompt
- Module: Wraps a signature with a prompting strategy (e.g., ChainOfThought)
- Teleprompter (MIPROv2): Optimizes prompts automatically based on data
"""

import os
import sys
from dotenv import load_dotenv

load_dotenv()

import dspy
from dspy.teleprompt import MIPROv2
from dspy.evaluate import answer_exact_match

# Configure Ollama with llama3.2
print("Configuring DSPy with Ollama (llama3.2)...")
dspy.configure(lm=dspy.LM("ollama/llama3.2"))


# Define Signature (the "interface" - what we want, not how to ask)
class AgentSignature(dspy.Signature):
    """Answer user questions accurately and concisely."""

    question = dspy.InputField(desc="The user's question")
    answer = dspy.OutputField(desc="A concise, factual answer")


# Create Module (wraps signature with ChainOfThought prompting strategy)
class QuestionAnsweringAgent(dspy.Module):
    def __init__(self):
        super().__init__()
        self.respond = dspy.ChainOfThought(AgentSignature)

    def forward(self, question):
        return self.respond(question=question)


# Define Metric (how to evaluate against golden answers)
def accuracy_metric(example, prediction, trace=None):
    expected = example.answer.lower().strip()
    predicted = prediction.answer.lower().strip()
    return expected in predicted or predicted in expected


# Load golden examples from LangSmith dataset
print("Loading golden examples from LangSmith...")
from langsmith import Client

client = Client()
DATASET_NAME = "langgraph-hello-world-golden"

dataset = client.read_dataset(dataset_name=DATASET_NAME)
if not dataset:
    print(f"Error: Dataset '{DATASET_NAME}' not found.")
    print("Run: python scripts/upload_dataset.py")
    sys.exit(1)

# Convert LangSmith examples to DSPy format
examples = []
for example in client.list_examples(dataset_id=dataset.id):
    question = example.inputs.get("question", "")
    answer = example.outputs.get("answer", "")
    if question and answer:
        examples.append(
            dspy.Example(question=question, answer=answer).with_inputs("question")
        )

print(f"Loaded {len(examples)} golden examples")

# Split into train and dev sets
train_size = int(len(examples) * 0.7)
trainset = examples[:train_size]
devset = examples[train_size:]

print(f"Training set: {len(trainset)} examples")
print(f"Dev set: {len(devset)} examples")

# Run Baseline (unoptimized)
print("\n" + "=" * 60)
print("BASELINE: Running unoptimized agent...")
print("=" * 60)

baseline_agent = QuestionAnsweringAgent()

baseline_correct = 0
for example in devset:
    prediction = baseline_agent(question=example.question)
    if accuracy_metric(example, prediction):
        baseline_correct += 1

baseline_score = baseline_correct / len(devset) if devset else 0
print(f"Baseline accuracy: {baseline_score:.2%}")

# Show what the baseline prompt looks like
print("\n--- Baseline Prompt (auto-generated by DSPy) ---")
prediction = baseline_agent(question=devset[0].question)
print(dspy.inspect_history(n=1))

# Compile with MIPROv2 (the "optimizer")
print("\n" + "=" * 60)
print("OPTIMIZING: Running MIPROv2 teleprompter...")
print("=" * 60)

teleprompter = MIPROv2(
    metric=accuracy_metric,
    auto="light",
    max_bootstrapped_demos=2,
    max_labeled_demos=2,
)

optimized_agent = teleprompter.compile(
    QuestionAnsweringAgent(),
    trainset=trainset,
)

# Evaluate optimized
print("\n" + "=" * 60)
print("OPTIMIZED: Running optimized agent...")
print("=" * 60)

optimized_correct = 0
for example in devset:
    prediction = optimized_agent(question=example.question)
    if accuracy_metric(example, prediction):
        optimized_correct += 1

optimized_score = optimized_correct / len(devset) if devset else 0
print(f"Optimized accuracy: {optimized_score:.2%}")

# Show the optimized prompt
print("\n--- Optimized Prompt (DSPy-generated) ---")
prediction = optimized_agent(question=devset[0].question)
print(dspy.inspect_history(n=1))

# Save the optimized program
optimized_agent.save("optimized_agent.json")
print("\nOptimized agent saved to: optimized_agent.json")

# Summary
print("\n" + "=" * 60)
print("SUMMARY")
print("=" * 60)
print(f"Baseline accuracy:   {baseline_score:.2%}")
print(f"Optimized accuracy: {optimized_score:.2%}")
print(f"Improvement: {(optimized_score - baseline_score):.2%}")
print("\nKey insight: DSPy automatically generated better prompts")
print("by optimizing instructions and selecting best few-shot examples.")
